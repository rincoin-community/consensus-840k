def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"), parse_float=Decimal)


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        raise ValueError(f"Refusing to write empty CSV: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=list(rows[0]),
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)


def iso_utc(unix_time: int) -> str:
    return (
        datetime.fromtimestamp(unix_time, timezone.utc)
        .isoformat(timespec="seconds")
        .replace("+00:00", "Z")
    )


def fmt_decimal(value: Decimal | float | int, places: int = 8) -> str:
    decimal = D(str(value))
    return f"{decimal.quantize(D(1).scaleb(-places)):f}"


def fmt_compact(value: Decimal | float | int, places: int = 4) -> str:
    decimal = D(str(value))
    return f"{decimal.quantize(D(1).scaleb(-places)):f}"


def percentile(values: list[float | int], fraction: float) -> float:
    if not values:
        raise ValueError("Cannot calculate percentile of an empty sequence")
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return float(ordered[lower])
    weight = position - lower
    return float(ordered[lower]) * (1 - weight) + float(ordered[upper]) * weight


def stats(values: list[float | int]) -> dict[str, float]:
    if not values:
        return {name: math.nan for name in ("mean", "median", "minimum", "maximum", "p10", "p90")}
    return {
        "mean": statistics.fmean(values),
        "median": statistics.median(values),
        "minimum": float(min(values)),
        "maximum": float(max(values)),
        "p10": percentile(values, 0.10),
        "p90": percentile(values, 0.90),
    }


def generated_header(source: str) -> str:
    return (
        "<!-- Generated by scripts/analyze_empirical_snapshot.py "
        f"from {source}. Do not edit by hand. -->\n\n"
    )


def md_table(
    headers: list[str],
    rows: list[list[str]],
    alignments: list[str],
    column_relative_widths: list[int] | None = None,
) -> str:
    markers = {"left": ":---", "center": ":---:", "right": "---:"}
    if len(headers) != len(alignments):
        raise ValueError("Markdown header/alignment length mismatch")
    if column_relative_widths is not None:
        if any(
            isinstance(width, bool) or not isinstance(width, int) or width <= 0
            for width in column_relative_widths
        ):
            raise ValueError("Markdown table column widths must be positive integers")
    for row in rows:
        if len(row) != len(headers):
            raise ValueError("Markdown table row length mismatch")
    lines = [
        "| " + " | ".join(headers) + " |",
        "|" + "|".join(markers[item] for item in alignments) + "|",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    table = "\n".join(lines) + "\n"
    if column_relative_widths is None:
        return table
    widths = ",".join(str(width) for width in column_relative_widths)
    return table + f'\n: {{tbl-colwidths="[{widths}]"}}\n'


def write_include(
    root: Path,
    name: str,
    source: str,
    headers: list[str],
    rows: list[list[str]],
    alignments: list[str],
    column_relative_widths: list[int] | None = None,
) -> None:
    path = root / "includes" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        generated_header(source)
        + md_table(
            headers,
            rows,
            alignments,
            column_relative_widths=column_relative_widths,
        ),
        encoding="utf-8",
    )


def source_entry(manifest: dict[str, Any], filename: str) -> dict[str, Any]:
    matches = [
        item for item in manifest["files"] if str(item["path"]).endswith("/" + filename)
    ]
    if len(matches) != 1:
        raise ValueError(f"Expected one manifest entry for {filename}, found {len(matches)}")
    return matches[0]


def verify_frozen_sources(root: Path, manifest: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for item in manifest["files"]:
        path = root / item["path"]
        actual = sha256(path)
        if actual != item["sha256"]:
            raise ValueError(f"Frozen source hash mismatch: {path}")
        rows.append(
            {
                "path": item["path"],
                "source_url": item["source_url"],
                "retrieved_utc": item["retrieved_utc"],
                "sha256": actual,
                "bytes": item["bytes"],
                "http_status": item["http_status"],
                "evidence_class": "frozen source response",
            }
        )
    return rows


def block_history(
    root: Path,
    snapshot_dir: Path,
    config: dict[str, Any],
) -> tuple[dict[int, dict[str, Any]], dict[int, int], list[dict[str, Any]], list[dict[str, Any]]]:
    empirical = config["empirical_security"]
    windows = [int(value) for value in empirical["history_windows_days"]]
    tip = read_json(snapshot_dir / "node_tip_block.json")
    tip_time = int(tip["header"]["time"])
    cutoffs = {days: tip_time - days * 86400 for days in windows}
    rolling_blocks = int(empirical["rolling_hashrate_window_blocks"])

    accumulators: dict[int, dict[str, Any]] = {}
    for days in windows:
        accumulators[days] = {
            "difficulty": [],
            "hashrate_hps": [],
            "block_interval_seconds": [],
            "non_coinbase_transactions": [],
            "total_fees_base_units": [],
            "fee_share_pct": [],
            "total_subsidy_base_units": 0,
            "total_fees_sum_base_units": 0,
            "zero_transaction_blocks": 0,
            "first_time": None,
            "last_time": None,
            "blocks": 0,
        }

    history_path = snapshot_dir / "node_block_history_365d.jsonl.gz"
    hashrate_path = root / "data" / f"{REVISION}hashrate_history.csv.gz"
    fee_path = root / "data" / f"{REVISION}fee_per_block_history.csv.gz"
    hashrate_path.parent.mkdir(parents=True, exist_ok=True)

    rolling: deque[tuple[int, int, int]] = deque()
    previous_time: int | None = None
    transaction_block_times: dict[int, int] = {}
    daily_hashrates: dict[str, list[float]] = defaultdict(list)
    daily_fees: dict[str, list[int]] = defaultdict(list)

    with (
        gzip.open(history_path, "rt", encoding="utf-8") as source,
        gzip.open(hashrate_path, "wt", newline="", encoding="utf-8") as hash_output,
        gzip.open(fee_path, "wt", newline="", encoding="utf-8") as fee_output,
    ):
        hash_writer = csv.DictWriter(
            hash_output,
            fieldnames=[
                "height",
                "time_utc",
                "difficulty",
                "block_interval_seconds",
                f"rolling_{rolling_blocks}_block_hashrate_hps",
                f"rolling_{rolling_blocks}_block_hashrate_mhps",
            ],
            lineterminator="\n",
        )
        fee_writer = csv.DictWriter(
            fee_output,
            fieldnames=[
                "height",
                "time_utc",
                "subsidy_base_units",
                "total_fees_base_units",
                "total_fees_rin",
                "non_coinbase_transactions",
                "fee_share_of_miner_revenue_pct",
            ],
            lineterminator="\n",
        )
        hash_writer.writeheader()
        fee_writer.writeheader()

        for line in source:
            record = json.loads(line)
            height = int(record["height"])
            block_time = int(record["time"])
            chainwork = int(record["chainwork"], 16)
            difficulty = float(record["difficulty"])
            subsidy = int(record["subsidy_base_units"])
            total_fees = int(record["total_fees_base_units"])
            transaction_count = int(record["non_coinbase_transactions"])
            interval = block_time - previous_time if previous_time is not None else None
            previous_time = block_time

            rolling.append((height, block_time, chainwork))
            if len(rolling) > rolling_blocks + 1:
                rolling.popleft()
            rolling_hashrate: float | None = None
            if len(rolling) == rolling_blocks + 1:
                elapsed = block_time - rolling[0][1]
                work = chainwork - rolling[0][2]
                if elapsed > 0 and work > 0:
                    rolling_hashrate = work / elapsed

            timestamp = iso_utc(block_time)
            fee_share = (
                D(total_fees) * D(100) / D(subsidy + total_fees)
                if subsidy + total_fees
                else D(0)
            )
            hash_writer.writerow(
                {
                    "height": height,
                    "time_utc": timestamp,
                    "difficulty": fmt_decimal(difficulty, 12),
                    "block_interval_seconds": "" if interval is None else interval,
                    f"rolling_{rolling_blocks}_block_hashrate_hps": (
                        "" if rolling_hashrate is None else fmt_decimal(rolling_hashrate, 4)
                    ),
                    f"rolling_{rolling_blocks}_block_hashrate_mhps": (
                        "" if rolling_hashrate is None else fmt_decimal(rolling_hashrate / 1_000_000, 8)
                    ),
                }
            )
            fee_writer.writerow(
                {
                    "height": height,
                    "time_utc": timestamp,
                    "subsidy_base_units": subsidy,
                    "total_fees_base_units": total_fees,
                    "total_fees_rin": fmt_decimal(D(total_fees) / COIN),
                    "non_coinbase_transactions": transaction_count,
                    "fee_share_of_miner_revenue_pct": fmt_decimal(fee_share, 12),
                }
            )

            day = timestamp[:10]
            if rolling_hashrate is not None:
                daily_hashrates[day].append(rolling_hashrate)
            daily_fees[day].append(total_fees)
            if transaction_count:
                transaction_block_times[height] = block_time

            for days, cutoff in cutoffs.items():
                if block_time < cutoff:
                    continue
                accumulator = accumulators[days]
                accumulator["blocks"] += 1
                accumulator["first_time"] = (
                    block_time
                    if accumulator["first_time"] is None
                    else min(accumulator["first_time"], block_time)
                )
                accumulator["last_time"] = (
                    block_time
                    if accumulator["last_time"] is None
                    else max(accumulator["last_time"], block_time)
                )
                accumulator["difficulty"].append(difficulty)
                if rolling_hashrate is not None:
                    accumulator["hashrate_hps"].append(rolling_hashrate)
                if interval is not None:
                    accumulator["block_interval_seconds"].append(interval)
                accumulator["non_coinbase_transactions"].append(transaction_count)
                accumulator["total_fees_base_units"].append(total_fees)
                accumulator["fee_share_pct"].append(float(fee_share))
                accumulator["total_subsidy_base_units"] += subsidy
                accumulator["total_fees_sum_base_units"] += total_fees
                if transaction_count == 0:
                    accumulator["zero_transaction_blocks"] += 1

    daily_hash_rows = [
        {
            "date_utc": day,
            "mean_rolling_hashrate_hps": fmt_decimal(statistics.fmean(values), 4),
            "mean_rolling_hashrate_mhps": fmt_decimal(statistics.fmean(values) / 1_000_000, 8),
            "observations": len(values),
        }
        for day, values in sorted(daily_hashrates.items())
    ]
    daily_fee_rows = [
        {
            "date_utc": day,
            "mean_total_fee_base_units_per_block": fmt_decimal(statistics.fmean(values), 4),
            "median_total_fee_base_units_per_block": fmt_decimal(statistics.median(values), 4),
            "mean_total_fee_rin_per_block": fmt_decimal(D(str(statistics.fmean(values))) / COIN),
            "blocks": len(values),
        }
        for day, values in sorted(daily_fees.items())
    ]
    write_csv(root / "data" / f"{REVISION}daily_hashrate_history.csv", daily_hash_rows)
    write_csv(root / "data" / f"{REVISION}daily_fee_history.csv", daily_fee_rows)
    return accumulators, transaction_block_times, daily_hash_rows, daily_fee_rows


def exact_transaction_fees(
    snapshot_dir: Path,
    transaction_block_times: dict[int, int],
    tip_time: int,
    windows: list[int],
) -> tuple[dict[int, list[int]], int]:
    fees_by_window = {days: [] for days in windows}
    total = 0
    path = snapshot_dir / "node_transaction_fees_365d.jsonl.gz"
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for line in handle:
            record = json.loads(line)
            height = int(record["height"])
            block_time = transaction_block_times[height]
            fee = int(record["fee_base_units"])
            total += fee
            for days in windows:
                if block_time >= tip_time - days * 86400:
                    fees_by_window[days].append(fee)
    return fees_by_window, total


def orphan_baseline(
    root: Path,
    snapshot_dir: Path,
    tip_time: int,
    windows: list[int],
) -> dict[int, dict[str, Any]]:
    path = snapshot_dir / "explorer_last_orphans_365d.jsonl.gz"
    records: list[dict[str, Any]] = []
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for line in handle:
            records.append(json.loads(line))
    write_csv(
        root / "data" / f"{REVISION}orphan_history.csv",
        [
            {
                "block_index": item["blockindex"],
                "block_hash": item["blockhash"],
                "previous_block_hash": item["prev_blockhash"],
                "reorg_depth": item["reorg_depth"],
                "transaction_count": item["tx_count"],
                "amount_rin": item["amount"],
                "timestamp_unix": item["timestamp"],
                "timestamp_utc": iso_utc(int(item["timestamp"])),
                "evidence_class": "directly observed explorer orphan index",
            }
            for item in records
        ],
    )
    summaries: dict[int, dict[str, Any]] = {}
    for days in windows:
        selected = [
            item
            for item in records
            if int(item["timestamp"]) >= tip_time - days * 86400
        ]
        depths = [int(item["reorg_depth"]) for item in selected]
        summaries[days] = {
            "count": len(selected),
            "depth": stats(depths) if depths else None,
            "coverage_status": (
                "complete for the explorer's returned orphan index; endpoint "
                "exhausted below its 100-record page limit, but index retention "
                "and pre-index history were not independently verified"
            ),
        }
    write_csv(
        root / "data" / f"{REVISION}orphan_baseline.csv",
        [
            {
                "window_days": days,
                "indexed_orphaned_blocks": summary["count"],
                "reorg_depth_mean": (
                    fmt_decimal(summary["depth"]["mean"], 4)
                    if summary["depth"] is not None
                    else ""
                ),
                "reorg_depth_median": (
                    fmt_decimal(summary["depth"]["median"], 4)
                    if summary["depth"] is not None
                    else ""
                ),
                "reorg_depth_p90": (
                    fmt_decimal(summary["depth"]["p90"], 4)
                    if summary["depth"] is not None
                    else ""
                ),
                "reorg_depth_maximum": (
                    fmt_decimal(summary["depth"]["maximum"], 4)
                    if summary["depth"] is not None
                    else ""
                ),
                "coverage_status": summary["coverage_status"],
                "evidence_class": "directly observed explorer orphan index",
            }
            for days, summary in sorted(summaries.items())
        ],
    )
    return summaries


