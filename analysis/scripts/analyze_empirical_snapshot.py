def hashrate_to_mh(value: Any, unit: str) -> Decimal:
    number = D(str(value or 0))
    normalized = unit.lower()
    if normalized == "mh":
        return number
    if normalized == "kh":
        return number / D(1000)
    if normalized in {"hash", "h"}:
        return number / D(1_000_000)
    raise ValueError(f"Unsupported hashrate unit: {unit}")


