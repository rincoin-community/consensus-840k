def greedy_rental_selection(
    rigs: list[dict[str, Any]],
    required_mh: Decimal,
    blocks: int,
) -> dict[str, Any]:
    if required_mh <= 0:
        return {
            "sufficient": True,
            "selected_mh": D(0),
            "rigs": 0,
            "theoretical_btc": D(0),
            "minimum_btc": D(0),
        }
    selected_mh = D(0)
    theoretical = D(0)
    minimum = D(0)
    selected = 0
    hours = D(blocks) / D(60)
    for rig in rigs:
        selected += 1
        selected_mh += rig["advertised_mh"]
        theoretical += rig["daily_cost_btc"] * hours / D(24)
        minimum += (
            rig["daily_cost_btc"] * max(hours, rig["minimum_hours"]) / D(24)
        )
        if selected_mh > required_mh:
            break
    return {
        "sufficient": selected_mh > required_mh,
        "selected_mh": selected_mh,
        "rigs": selected,
        "theoretical_btc": theoretical,
        "minimum_btc": minimum,
    }


def export_attack_capacity(
    root: Path,
    config: dict[str, Any],
    current_hashrate_mh: Decimal,
    rental_summary: dict[str, Any],
    rigs: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    empirical = config["empirical_security"]
    rental = D(rental_summary["advertised_available_mh"])
    btc_usd = D(rental_summary["btc_usd"])
    rows: list[dict[str, Any]] = []
    for reduction in empirical["honest_hashrate_reduction_stress_pct"]:
        honest = current_hashrate_mh * (D(100) - D(reduction)) / D(100)
        for owned in empirical["owned_hashrate_stress_mh"]:
            owned_hash = D(owned)
            attack_hash = rental + owned_hash
            for blocks in empirical["rental_horizons_blocks"]:
                required_rental = max(D(0), honest - owned_hash)
                selection = greedy_rental_selection(rigs, required_rental, int(blocks))
                rows.append(
                    {
                        "honest_hashrate_reduction_stress_pct": reduction,
                        "honest_hashrate_mhps": fmt_decimal(honest, 6),
                        "configured_owned_hashrate_mhps": fmt_decimal(owned_hash, 6),
                        "visible_rental_hashrate_mhps": fmt_decimal(rental, 6),
                        "rental_pct_pre_existing_honest_hashrate": fmt_decimal(
                            rental * D(100) / honest if honest else D(0), 4
                        ),
                        "rental_pct_combined_honest_plus_rental_hashrate": fmt_decimal(
                            rental * D(100) / (honest + rental) if honest + rental else D(0),
                            4,
                        ),
                        "rental_plus_owned_hashrate_mhps": fmt_decimal(attack_hash, 6),
                        "additional_hash_required_to_exceed_honest_mhps": fmt_decimal(
                            max(D(0), honest - attack_hash), 6
                        ),
                        "visible_rental_capacity_alone_sufficient": str(rental > honest).lower(),
                        "rental_plus_owned_capacity_sufficient": str(
                            attack_hash > honest
                        ).lower(),
                        "analytical_horizon_blocks": blocks,
                        "greedy_selected_rigs": selection["rigs"],
                        "greedy_selected_rental_hashrate_mhps": fmt_decimal(
                            selection["selected_mh"], 6
                        ),
                        "visible_depth_sufficient_for_threshold": str(
                            selection["sufficient"]
                        ).lower(),
                        "theoretical_prorated_threshold_cost_btc": (
                            fmt_decimal(selection["theoretical_btc"], 12)
                            if selection["sufficient"]
                            else ""
                        ),
                        "actual_minimum_lease_threshold_cost_btc": (
                            fmt_decimal(selection["minimum_btc"], 12)
                            if selection["sufficient"]
                            else ""
                        ),
                        "actual_minimum_lease_threshold_cost_usd": (
                            fmt_decimal(selection["minimum_btc"] * btc_usd, 6)
                            if selection["sufficient"]
                            else ""
                        ),
                        "evidence_class": (
                            "observed rental asks plus speculative honest-hash reduction "
                            "and owned-hash stress inputs"
                        ),
                    }
                )
    write_csv(root / "data" / f"{REVISION}rental_attack_capacity.csv", rows)
    baseline_rows = [
        row
        for row in rows
        if D(str(row["configured_owned_hashrate_mhps"])) == 0
        and int(row["analytical_horizon_blocks"]) == 144
    ]
    write_include(
        root,
        f"{REVISION}rental_attack_capacity_table.qmd",
        f"data/{REVISION}rental_attack_capacity.csv",
        [
            "Honest-hash reduction",
            "Honest MH/s",
            "Rental / honest",
            "Rental / combined",
            "Rental alone exceeds honest?",
            "Min 24 h ask cost if sufficient",
        ],
        [
            [
                f"{row['honest_hashrate_reduction_stress_pct']}%",
                row["honest_hashrate_mhps"],
                f"{row['rental_pct_pre_existing_honest_hashrate']}%",
                f"{row['rental_pct_combined_honest_plus_rental_hashrate']}%",
                row["visible_rental_capacity_alone_sufficient"],
                (
                    f"${row['actual_minimum_lease_threshold_cost_usd']}"
                    if row["actual_minimum_lease_threshold_cost_usd"]
                    else "insufficient visible depth"
                ),
            ]
            for row in baseline_rows
        ],
        ["right", "right", "right", "right", "center", "right"],
    )
    return rows


def parse_book(payload: Any, venue: str) -> tuple[list[tuple[Decimal, Decimal]], list[tuple[Decimal, Decimal]]]:
    if venue == "NestEx":
        bids = [(D(price), D(str(amount))) for price, amount in payload["bids"].items()]
        asks = [(D(price), D(str(amount))) for price, amount in payload["asks"].items()]
    else:
        bids = [(D(str(price)), D(str(amount))) for price, amount in payload["bids"]]
        asks = [(D(str(price)), D(str(amount))) for price, amount in payload["asks"]]
    return sorted(bids, reverse=True), sorted(asks)


def walk_sell(
    bids: list[tuple[Decimal, Decimal]], quantity: Decimal
) -> dict[str, Any]:
    remaining = quantity
    proceeds = D(0)
    worst: Decimal | None = None
    for price, available in bids:
        filled = min(remaining, available)
        proceeds += filled * price
        remaining -= filled
        if filled:
            worst = price
        if remaining <= 0:
            break
    filled_total = quantity - remaining
    average = proceeds / filled_total if filled_total else D(0)
    return {
        "requested": quantity,
        "filled": filled_total,
        "remaining": remaining,
        "proceeds": proceeds,
        "average_price": average,
        "worst_price": worst,
        "complete": remaining <= 0,
    }


