def validate_outputs(
    root: Path,
    config: dict[str, Any],
    manifest: dict[str, Any],
    summaries: dict[int, dict[str, Any]],
    transaction_fee_total: int,
    rental: dict[str, Any],
) -> None:
    manifest_history = source_entry(manifest, "node_block_history_365d.jsonl.gz")
    expected_fee_total = 0
    with gzip.open(root / manifest_history["path"], "rt", encoding="utf-8") as handle:
        for line in handle:
            expected_fee_total += int(json.loads(line)["total_fees_base_units"])
    if transaction_fee_total != expected_fee_total:
        raise ValueError("Transaction-fee total does not match block-history total")

    primary = summaries[int(config["empirical_security"]["primary_fee_window_days"])]
    fee_cases = {item["id"]: item for item in config["security_economics"]["fee_cases"]}
    if int(fee_cases["low"]["fee_per_block_base_units"]) != round(
        primary["block_fees"]["median"]
    ):
        raise ValueError("Low fee case is not anchored to the observed all-block median")
    if int(fee_cases["base"]["fee_per_block_base_units"]) != round(
        primary["block_fees"]["mean"]
    ):
        raise ValueError("Base fee case is not anchored to the observed all-block mean")
    if int(fee_cases["high"]["fee_per_block_base_units"]) != round(
        primary["active_block_fees"]["p90"]
    ):
        raise ValueError(
            "High fee case is not anchored to the observed active-block p90"
        )
    history = read_csv(root / "data" / f"{REVISION}historical_network_baseline.csv")
    if len(history) != 3:
        raise ValueError("Expected 30/90/365-day historical summaries")

    mrr = read_json(
        root
        / config["empirical_security"]["snapshot_path"]
        / "mrr_rinhash_rigs.json"
    )
    api_capacity = hashrate_to_mh(
        mrr["data"]["stats"]["available"]["hash"]["hash"],
        mrr["data"]["stats"]["available"]["hash"]["type"],
    )
    if abs(api_capacity - D(rental["advertised_available_mh"])) > D("0.000001"):
        raise ValueError("Rental aggregate mismatch")
    if rental["all_capacity_24h_cost_btc"] != D("0.000352921232500000"):
        raise ValueError("Unexpected all-capacity 24-hour rental ask")
    if rental["all_capacity_minimum_contract_cost_btc"] != D(
        "0.00009093210531250000"
    ):
        raise ValueError("Unexpected sum of listing minimum contractual prices")

    required = [
        f"data/{REVISION}empirical_network_snapshot.csv",
        f"data/{REVISION}historical_network_baseline.csv",
        f"data/{REVISION}hashrate_history.csv.gz",
        f"data/{REVISION}fee_per_block_history.csv.gz",
        f"data/{REVISION}orphan_history.csv",
        f"data/{REVISION}orphan_baseline.csv",
        f"data/{REVISION}rental_market_listings.csv",
        f"data/{REVISION}rental_cost_curve.csv",
        f"data/{REVISION}rental_cost_reconciliation.csv",
        f"data/{REVISION}rental_attack_capacity.csv",
        f"data/{REVISION}fee_replacement_calibrated.csv",
        f"data/{REVISION}exchange_liquidity.csv",
        f"data/{REVISION}hardware_benchmarks.csv",
        f"data/{REVISION}empirical_scenario_security_comparison.csv",
        f"figures/{REVISION}empirical_hashrate_history_365d.png",
        f"figures/{REVISION}empirical_fee_per_block_history_365d.png",
        f"figures/{REVISION}rental_cost_curve.png",
        f"figures/{REVISION}rental_network_hash_ratio.png",
        f"figures/{REVISION}market_depth_vs_daily_issuance.png",
        f"figures/{REVISION}empirical_scenario_security_activation.png",
        f"includes/{REVISION}rental_listing_audit_table.qmd",
        f"includes/{REVISION}rental_cost_reconciliation_table.qmd",
    ]
    for relative in required:
        path = root / relative
        if not path.exists() or path.stat().st_size == 0:
            raise ValueError(f"Missing empirical artifact: {relative}")


def main() -> None:
    root = Path.cwd()
    config = monetary.load_config(root)
    snapshot_dir = root / config["empirical_security"]["snapshot_path"]
    manifest = read_json(snapshot_dir / "SOURCE_MANIFEST.json")
    source_rows = verify_frozen_sources(root, manifest)
    write_csv(root / "data" / f"{REVISION}empirical_source_manifest.csv", source_rows)

    accumulators, transaction_block_times, daily_hash, daily_fees = block_history(
        root, snapshot_dir, config
    )
    tip = read_json(snapshot_dir / "node_tip_block.json")
    windows = [int(value) for value in config["empirical_security"]["history_windows_days"]]
    transaction_fees, transaction_fee_total = exact_transaction_fees(
        snapshot_dir,
        transaction_block_times,
        int(tip["header"]["time"]),
        windows,
    )
    orphan_summaries = orphan_baseline(
        root,
        snapshot_dir,
        int(tip["header"]["time"]),
        windows,
    )
    _, summaries = export_historical_baseline(
        root,
        snapshot_dir,
        config,
        accumulators,
        transaction_fees,
        orphan_summaries,
    )

    mining = read_json(snapshot_dir / "node_mining_info.json")
    current_hashrate_mh = D(str(mining["networkhashps"])) / D(1_000_000)
    kraken = read_json(snapshot_dir / "kraken_xbt_usd_ticker.json")
    btc_usd = D(kraken["result"]["XXBTZUSD"]["c"][0])
    rental, rigs, rental_curve = parse_rental_market(
        root, snapshot_dir, config, current_hashrate_mh, btc_usd
    )
    attack_rows = export_attack_capacity(
        root, config, current_hashrate_mh, rental, rigs
    )

    subsidy = D(tip["stats"]["subsidy"]) / COIN
    daily_issuance = (
        subsidy * D(86400) / D(config["network"]["target_block_seconds"])
    )
    liquidity_rows, liquidity = export_exchange_liquidity(
        root, snapshot_dir, config, daily_issuance
    )
    export_current_snapshot(
        root, snapshot_dir, manifest, summaries, rental, liquidity, config
    )
    export_hardware_protocol(root)
    export_fee_replacement(root, summaries, config)
    scenario_rows = export_empirical_scenario_comparison(
        root, snapshot_dir, summaries, config
    )
    export_empirical_figures(
        root,
        daily_hash,
        daily_fees,
        rental_curve,
        attack_rows,
        liquidity_rows,
        scenario_rows,
    )
    validate_outputs(
        root,
        config,
        manifest,
        summaries,
        transaction_fee_total,
        rental,
    )


if __name__ == "__main__":
    main()
