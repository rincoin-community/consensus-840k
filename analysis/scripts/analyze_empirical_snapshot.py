def draw_line_chart(
    path: Path,
    title: str,
    x_label: str,
    y_label: str,
    series: list[tuple[str, tuple[int, int, int], list[tuple[float, float]]]],
) -> None:
    width, height = 1800, 930
    left, right, top, bottom = 145, 420, 100, 120
    plot_width = width - left - right
    plot_height = height - top - bottom
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    try:
        title_font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 30
        )
        font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 18
        )
        small = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 15
        )
    except OSError:
        title_font = font = small = ImageFont.load_default()

    all_points = [point for _, _, points in series for point in points]
    x_min = min((point[0] for point in all_points), default=0)
    x_max = max((point[0] for point in all_points), default=1)
    y_min = min((point[1] for point in all_points), default=0)
    y_max = max((point[1] for point in all_points), default=1)
    if x_max == x_min:
        x_max = x_min + 1
    if y_max == y_min:
        y_max = y_min + 1
    y_padding = (y_max - y_min) * 0.05
    y_min = min(0, y_min - y_padding)
    y_max += y_padding

    draw.text((left, 28), title, fill=(20, 20, 20), font=title_font)
    draw.text((20, 70), y_label, fill=(20, 20, 20), font=font)
    draw.text(
        (left + plot_width // 2 - 120, height - 50),
        x_label,
        fill=(20, 20, 20),
        font=font,
    )
    for index in range(6):
        x = left + index * plot_width / 5
        y = top + index * plot_height / 5
        draw.line((x, top, x, top + plot_height), fill=(225, 225, 225))
        draw.line((left, y, left + plot_width, y), fill=(225, 225, 225))
        x_value = x_min + (x_max - x_min) * index / 5
        y_value = y_max - (y_max - y_min) * index / 5
        draw.text((x - 15, top + plot_height + 12), f"{x_value:.0f}", fill=(40, 40, 40), font=small)
        draw.text((22, y - 8), f"{y_value:.4g}", fill=(40, 40, 40), font=small)
    draw.rectangle((left, top, left + plot_width, top + plot_height), outline=(80, 80, 80))

    def position(point: tuple[float, float]) -> tuple[float, float]:
        x, y = point
        return (
            left + (x - x_min) / (x_max - x_min) * plot_width,
            top + plot_height - (y - y_min) / (y_max - y_min) * plot_height,
        )

    legend_x = left + plot_width + 35
    draw.text((legend_x, top), "Series", fill=(20, 20, 20), font=title_font)
    legend_y = top + 48
    for label, color, points in series:
        coordinates = [position(point) for point in points]
        if len(coordinates) > 1:
            draw.line(coordinates, fill=color, width=3)
        draw.rectangle((legend_x, legend_y, legend_x + 26, legend_y + 16), fill=color)
        wrapped = textwrap.wrap(label, width=34) or [label]
        for offset, text in enumerate(wrapped):
            draw.text(
                (legend_x + 36, legend_y + offset * 20),
                text,
                fill=(20, 20, 20),
                font=small,
            )
        legend_y += max(40, len(wrapped) * 22 + 8)
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


def draw_bar_chart(
    path: Path,
    title: str,
    y_label: str,
    labels: list[str],
    values: list[float],
    color: tuple[int, int, int],
) -> None:
    width, height = 1650, 900
    left, right, top, bottom = 150, 80, 105, 190
    plot_width = width - left - right
    plot_height = height - top - bottom
    image = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(image)
    try:
        title_font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 29
        )
        font = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 17
        )
        small = ImageFont.truetype(
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", 14
        )
    except OSError:
        title_font = font = small = ImageFont.load_default()
    maximum = max(values, default=1) * 1.10 or 1
    draw.text((left, 28), title, fill=(20, 20, 20), font=title_font)
    draw.text((20, 72), y_label, fill=(20, 20, 20), font=font)
    for index in range(6):
        y = top + index * plot_height / 5
        value = maximum * (5 - index) / 5
        draw.line((left, y, left + plot_width, y), fill=(225, 225, 225))
        draw.text((28, y - 8), f"{value:.4g}", fill=(40, 40, 40), font=small)
    slot = plot_width / max(1, len(values))
    for index, (label, value) in enumerate(zip(labels, values)):
        x0 = left + index * slot + slot * 0.15
        x1 = left + (index + 1) * slot - slot * 0.15
        y0 = top + plot_height - value / maximum * plot_height
        draw.rectangle((x0, y0, x1, top + plot_height), fill=color)
        draw.text((x0, y0 - 24), f"{value:.4g}", fill=(30, 30, 30), font=small)
        for line_index, line in enumerate(textwrap.wrap(label, width=15)):
            draw.text(
                (x0, top + plot_height + 16 + line_index * 18),
                line,
                fill=(30, 30, 30),
                font=small,
            )
    draw.rectangle((left, top, left + plot_width, top + plot_height), outline=(80, 80, 80))
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path)


